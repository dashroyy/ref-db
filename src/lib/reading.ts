export const sourceById = (id: string) => SOURCES.find((s) => s.id === id);

/** A reference-list entry: "who, title, edition and year." */
export const citation = (s: Source) => `${s.who}, ${s.title}${s.pub ? `, ${s.pub}` : ''}.`.replace(/, \(/, ' (');

export interface Doc { path: string; title: string; text: string }
/** The pages whose text cites the source. */
export const citedBy = (s: Source, docs: Doc[]) => {
  const res = s.find.map((f) => new RegExp(f));
  return docs.filter((d) => res.some((r) => r.test(d.text))).map(({ path, title }) => ({ path, title }));
};

/** Sources that match a search, a category, a page, and the free and start filters. */
export function filterSources<T extends Source & { pages?: { path: string }[] }>(
  list: T[], o: { q?: string; cat?: string; free?: boolean; start?: boolean; page?: string },
) {
  const q = (o.q ?? '').trim().toLowerCase();
  return list.filter((s) => (!o.cat || s.cat === o.cat) && (!o.free || s.free) && (!o.start || s.start)
    && (!o.page || (s.pages ?? []).some((p) => p.path === o.page))
    && (!q || `${s.title} ${s.who} ${s.pub} ${s.what} ${s.why} ${KINDS[s.kind]}`.toLowerCase().includes(q)));
}
